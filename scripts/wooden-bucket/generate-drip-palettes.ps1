# Sample exact opaque colors from the two fluid textures; never edit the PNGs.
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
$root = (Resolve-Path "$PSScriptRoot/../..").Path
$lines = @('package dev.poptartking.poptartcore.decoration.client;', '', '// Generated by scripts/wooden-bucket/generate-drip-palettes.ps1.', 'public final class TapperDripPalettes {', '    private TapperDripPalettes() {}')
foreach ($name in @('resin', 'maple_syrup')) {
    $image = [System.Drawing.Bitmap]::new("$root/src/main/resources/assets/poptartcore/textures/block/fluid/${name}_layer.png")
    $colors = [System.Collections.Generic.SortedSet[string]]::new()
    try {
        for ($y = 0; $y -lt $image.Height; $y++) {
            for ($x = 0; $x -lt $image.Width; $x++) {
                $c = $image.GetPixel($x, $y)
                if ($c.A -gt 0) { [void]$colors.Add(('0x{0:X2}{1:X2}{2:X2}' -f $c.R, $c.G, $c.B)) }
            }
        }
    } finally { $image.Dispose() }
    if ($colors.Count -eq 0) { throw "Empty palette: $name" }
    $lines += "    public static final int[] $($name.ToUpperInvariant()) = { $($colors -join ', ') };"
}
$lines += '}'
[IO.File]::WriteAllText("$root/src/main/java/dev/poptartking/poptartcore/decoration/client/TapperDripPalettes.java", ($lines -join "`n") + "`n")
